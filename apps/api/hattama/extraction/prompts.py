def events_user_message(meeting_line: str, participants_line: str, state: str, context_lines: list[str],
                        window_lines: list[str]) -> str:
    parts = [meeting_line, f"Участники: {participants_line}", "Текущие задачи:", state or "(нет)"]
    if context_lines:
        parts += ["Контекст (предыдущие реплики, события из них НЕ извлекай):", *context_lines]
    parts += ["Новые реплики (извлекай события только из них):", "<<<РАСШИФРОВКА", *window_lines, "РАСШИФРОВКА>>>"]
    return "\n".join(parts)


def summary_user_message(meeting_line: str, window_lines: list[str]) -> str:
    return "\n".join([meeting_line, "<<<РАСШИФРОВКА", *window_lines, "РАСШИФРОВКА>>>"])


def format_segment_line(alias: str, speaker: str, text: str) -> str:
    return f"[{alias}] {speaker}: {text}"
